const ADVANCE = 6;

export function textWidth(text: string, height: number) { return text.length ? (text.length * ADVANCE - 2) * height / 6 : 0; }

/** Open polylines for `text` with its top-left corner at (x, y), letters `height` mm tall. */
export function strokeText(text: string, height: number, x = 0, y = 0): Point[][] {
  const scale = height / 6;
  return [...text.toUpperCase()].flatMap((char, index) => {
    const strokes = glyphs[char];
    if (!strokes) throw new Error(`Engraving font has no glyph for "${char}".`);
    return strokes.map(stroke => stroke.map(([gx, gy]) => ({ x: x + (index * ADVANCE + gx) * scale, y: y + gy * scale })));
  });
}
